void main() {
  setUpAll(() => L10n.loadFolder(Directory('assets/l10n')));

  test('every old text is in assets/l10n, the same once filled', () {
    final tables = {
      'main': oldTables(),
      'chat': oldTablesChat(),
      'media': oldTablesMedia(),
      'private': oldTablesPrivate(),
      'safety': oldTablesSafety(),
      'social': oldTablesSocial(),
      'join': oldTablesJoin(),
      'discover': oldTablesDiscover(),
      'typing': oldTablesTyping(),
    };
    var count = 0;
    for (final language in ['en', 'tr']) {
      for (final (table, key, json, tokens) in _keys) {
        final arguments = [for (var n = 1; n <= tokens.length; n++) 'ARG$n'];
        var old = tables[table]![language]![key]!;
        for (var n = 0; n < tokens.length; n++) {
          old = old.replaceAll(tokens[n], arguments[n]);
        }
        expect(
          L10n.fill(L10n.textOrNull(language, json)!, arguments),
          old,
          reason: '$table.$key ($json) in $language',
        );
        count++;
      }
      for (final MapEntry(:key, :value) in tables.entries) {
        expect(
          _keys.where((entry) => entry.$1 == key).length,
          value[language]!.length,
          reason: 'every key of the $key table is checked',
        );
      }
      final months = oldMonths()[language]!;
      for (var n = 0; n < 12; n++) {
        expect(L10n.textOrNull(language, 'monthShort${n + 1}'), months[n]);
      }
      for (final MapEntry(:key, :value) in oldLanguages()[language]!.entries) {
        expect(L10n.textOrNull(language, 'spokenLanguage_$key'), value);
      }
    }
    expect(count, greaterThan(1200));
    expect(L10n.textOrNull('tr', L10n.nameKey), 'Türkçe');
  });
}
